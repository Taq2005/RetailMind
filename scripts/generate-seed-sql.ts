/**
 * Writes db/seed.sql from the same deterministic generator the app uses.
 *
 *   npm run db:seed                 -> customers, products, connectors + the last 14 days of orders
 *   npm run db:seed -- --days=365   -> the full year (about 90k orders, 15 MB)
 */
import { writeFileSync } from "node:fs";
import { generateDB, orderRow, itemRow, N_DAYS, TODAY_IDX } from "../src/data/seed";

const arg = process.argv.find((a) => a.startsWith("--days="));
const days = Math.min(N_DAYS, Math.max(1, Number(arg?.split("=")[1] ?? 14)));
const from = N_DAYS - days;
const db = generateDB();

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const out: string[] = [];
out.push(`-- RetailMind demo seed (generated by scripts/generate-seed-sql.ts, do not edit by hand)`);
out.push(`-- Orders included: last ${days} day(s) up to 2026-11-13. Customers, products and connectors are complete.`);
out.push(`BEGIN;`);

const batch = (table: string, cols: string, rows: string[], size = 500) => {
  for (let i = 0; i < rows.length; i += size) {
    out.push(`INSERT INTO ${table} (${cols}) VALUES\n${rows.slice(i, i + size).join(",\n")};`);
  }
};

batch("customers", "id, name, email, segment, region, created_at", db.customers.map((c) => `(${c.id}, ${q(c.name)}, ${q(c.email)}, ${q(c.segment)}, ${q(c.region)}, ${q(c.created_at)})`));
batch("products", "id, name, category, cost_price, retail_price, stock_quantity, reorder_level", db.products.map((p) => `(${p.id}, ${q(p.name)}, ${q(p.category)}, ${p.cost_price.toFixed(2)}, ${p.retail_price.toFixed(2)}, ${p.stock_quantity}, ${p.reorder_level})`));
batch("connectors", "id, name, type, status, last_sync, host_masked, row_count", db.connectors.map((c) => `(${c.id}, ${q(c.name)}, ${q(c.type)}, ${q(c.status)}, ${q(c.last_sync)}, ${q(c.host_masked)}, ${c.row_count})`));

const orderRows: string[] = [];
const itemRows: string[] = [];
let nOrders = 0;
for (let i = 0; i < db.nOrders; i++) {
  if (db.o_day[i] < from) continue;
  const o = orderRow(db, i);
  orderRows.push(`(${o.id}, ${o.customer_id}, ${q(o.channel)}, ${q(o.order_date)}, ${q(o.status)}, ${o.total_amount.toFixed(2)}, ${o.discount_amount.toFixed(2)})`);
  nOrders++;
  for (let j = db.o_itemStart[i]; j < db.o_itemStart[i + 1]; j++) {
    const it = itemRow(db, j);
    itemRows.push(`(${it.id}, ${it.order_id}, ${it.product_id}, ${it.quantity}, ${it.unit_price.toFixed(2)}, ${it.profit_margin.toFixed(2)})`);
  }
}
batch("orders", "id, customer_id, channel, order_date, status, total_amount, discount_amount", orderRows);
batch("order_items", "id, order_id, product_id, quantity, unit_price, profit_margin", itemRows, 1000);
out.push(`COMMIT;`);
out.push(`-- ${nOrders} orders, ${itemRows.length} order items, ${db.customers.length} customers, ${db.products.length} products, ${db.connectors.length} connectors`);

writeFileSync(new URL("../db/seed.sql", import.meta.url), out.join("\n") + "\n");
console.log(`db/seed.sql: ${nOrders} orders, ${itemRows.length} items (days=${days}, today index ${TODAY_IDX})`);
